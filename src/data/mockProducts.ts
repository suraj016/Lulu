const inStock = (qty: number): Inventory => ({
  trackQuantity: true,
  availableQuantity: qty,
  allowBackorder: false,
});

const unlimited: Inventory = {
  trackQuantity: false,
  availableQuantity: 0,
  allowBackorder: false,
};

function image(
  id: string,
  fileName: string,
  alt: string,
  width = 1000,
  height = 1000,
): ProductImage {
  return {
    id,
    src: productImagePath(fileName),
    alt,
    width,
    height,
    mediaType: MediaType.Image,
    assetStatus: 'placeholder',
  };
}

function colorVariant(input: {
  productId: string;
  colorId: string;
  label: string;
  hex: string;
  sku: string;
  qty?: number;
  available?: boolean;
  imageIds: string[];
}): ProductVariant {
  return {
    id: `${input.productId}-${input.colorId}`,
    sku: input.sku,
    label: input.label,
    colorName: input.label,
    colorHex: input.hex,
    imageIds: input.imageIds,
    inventory: inStock(input.qty ?? 18),
    isAvailable: input.available ?? true,
  };
}

